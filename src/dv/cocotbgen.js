function tests(cfg, model, g) {
  const byTest = [];
  for (const s of model.scenarios) { if (!s.test) continue; let t = byTest.find(x => x.name === s.test); if (!t) byTest.push(t = { name: s.test, sc: [] }); t.sc.push(s); }
  return byTest.map(t => {
    const lines = [`@cocotb.test()`, `async def ${t.name.replace(/\W/g, '_')}(dut):`, `    """${t.sc.map(s => s.id + ' ' + s.title).join('; ').replace(/"/g, "'")}"""`, `    chk = Checker(dut, ${py(t.name)})`, `    rnd = _random.Random(SEED)`];
    if (g.kind === 'seq') lines.push('    m = Model()', '    await start_clock(dut)', '    await do_reset(dut, m)');
    if (g.kind === 'latch') lines.push('    m = Model()', '    await do_reset(dut, m)');
    for (const s of t.sc) {
      const b = g.body[s.id];
      lines.push(`    chk.scenario(${py(s.id)})   # ${s.title}: ${String(s.expected || '').replace(/\n/g, ' ')}`);
      lines.push(b ? b : `    pass   # no Python stimulus for ${s.id} yet`);
    }
    lines.push('    chk.finish()');
    return lines.join('\n');
  }).join('\n\n\n');
}

function makefile(root, cfg) {
  const srcs = cfg.dut.files.map(f => `VERILOG_SOURCES += $(abspath $(CURDIR)/../${String(f).replace(/\\/g, '/')})`).join('\n');
  const incs = (cfg.dut.incdirs || []).map(d => `COMPILE_ARGS += -I$(abspath $(CURDIR)/../${d})`).join('\n');
  const params = Object.entries(cfg.dut.params || {}).map(([k, v]) => `ifeq ($(SIM),icarus)\nCOMPILE_ARGS += -P${cfg.dut.top}.${k}=${v}\nelse\nEXTRA_ARGS += -G${k}=${v}\nendif`).join('\n');
  return `# cocotb Makefile for ${cfg.dut.top}: generated by 10xEngineers EDA
#   make                     all tests on Icarus
#   make SIM=verilator       on Verilator
#   make COCOTB_TEST_FILTER=smoke COCOTB_RANDOM_SEED=7
SIM ?= icarus
TOPLEVEL_LANG ?= verilog

${srcs}
${incs}

# cocotb 2.x names (cocotb 1.x reads TOPLEVEL / MODULE)
COCOTB_TOPLEVEL = ${cfg.dut.top}
TOPLEVEL = ${cfg.dut.top}
COCOTB_TEST_MODULES = test_${cfg.dut.top}
MODULE = test_${cfg.dut.top}

ifeq ($(SIM),icarus)
COMPILE_ARGS += -g2012
endif
ifeq ($(SIM),verilator)
EXTRA_ARGS += --timing -Wno-fatal -Wno-lint -Wno-style
endif
${params}

include $(shell cocotb-config --makefiles)/Makefile.sim
`;
}

function generate(root, cfg) {
  const dut = tb.resolveDut(tb.withDefaults(cfg), root, {}, f => fs.readFileSync(f, 'utf8'));
  const c = tb.withDefaults(cfg);
  const model = tb.buildModel(c, dut.ports, dut.paramValues);
  const gen = GEN[c.template] || custom;
  const g = gen(c, model);
  if (g.kind === 'unsupported-seq') {
    // custom sequential: give the clocked harness with a model class to fill in
    g.kind = 'seq';
    g.code = `\n\nIDLE = {${model.inputs.map(i => `${py(i.name)}: 0`).join(', ')}}\nINPUTS = {${model.inputs.map(i => `${py(i.name)}: ${i.width}`).join(', ')}}\nMODEL_WRITTEN = False\n\n\nclass Model:\n    """Write the reference model: state in reset()/step(), expected outputs in outputs()."""\n\n    def reset(self):\n        pass\n\n    def step(self, v):\n        pass\n\n    def outputs(self, v):\n        return {}   # {"port": expected_value}\n`;
    g.body = Object.fromEntries(model.scenarios.map(s => [s.id, `    assert MODEL_WRITTEN, "write the Model class in this file and set MODEL_WRITTEN = True"\n    await do_reset(dut, m)\n    for _ in range(ITERATIONS if ${py(s.test)} == "random" else 8):\n        await step(chk, dut, m, {k: rnd.getrandbits(w) for k, w in INPUTS.items()})`]));
  }
  const harness = g.kind === 'comb' ? COMB : g.kind === 'latch' ? LATCH : seqHarness(c);
  const text = header(c, model, c.options.random_iterations || 200) + g.code + harness + '\n\n' + tests(c, model, g) + '\n';
  const readme = `# cocotb testbench: ${c.dut.top}

Generated by 10xEngineers EDA from \`dvflow.json\` (template **${c.template}**). It uses the same tests, scenario IDs (${model.scenarios.map(s => s.id).join(', ')}) and requirements as the SystemVerilog testbench in \`tb/\` and the UVM testbench in \`uvm/\`.

| File | What it is |
|---|---|
| \`test_${c.dut.top}.py\` | Python reference model, stimulus per scenario, checker |
| \`Makefile\` | cocotb build for Icarus (default) or Verilator |

**Run from VS Code:** **DV: Run Test** → **cocotb testbench** → simulator → tests. This runs in the Docker toolchain, which has Python and cocotb, and opens the dashboard.

**Run by hand** (needs Python with cocotb, and a simulator):

\`\`\`
make                         # all tests, Icarus
make SIM=verilator
make COCOTB_TEST_FILTER=smoke COCOTB_RANDOM_SEED=7
\`\`\`

The model is written from the behaviour spec, not from the RTL, so a bug in the RTL can't hide in it. Regenerating overwrites \`test_${c.dut.top}.py\`; copy it first if you extend it.
`;
  return { files: { [`cocotb/test_${c.dut.top}.py`]: text, 'cocotb/Makefile': makefile(root, c), 'cocotb/README.md': readme }, template: c.template, scenarios: model.scenarios.length };
}

module.exports = { generate };
