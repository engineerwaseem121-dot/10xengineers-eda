'use strict';
/*
 * Formal harness generator: proves the DUT matches the template's reference model for EVERY input sequence.
 *   formal/<top>_formal.sv   DUT + reference model side by side; every DUT input is a free input of the harness;
 *                             one assertion per checked output, one cover per coverage bin
 *   formal/<top>.sby          SymbiYosys tasks: prove (k-induction: unbounded proof) and cover (bin reachability)
 * The model is the same one the SV / UVM / cocotb testbenches use, so a formal PASS means "matches the spec, for all
 * inputs", and a FAIL comes with a counterexample trace.
 */
const fs = require('fs');
const path = require('path');
const tb = require('./tbgen');

function generate(root, cfg0) {
  const cfg = tb.withDefaults(cfg0);
  const read = f => fs.readFileSync(f, 'utf8');
  let dut = tb.resolveDut(cfg, root, {}, read);
  // storage-heavy designs: check a small instance of the same RTL (4 entries x 4 bits). The solver's work grows
  // with every memory bit, and pointer, flag and ordering bugs show up the same way in a small FIFO.
  let small = null;
  if (cfg.template === 'fifo' || cfg.template === 'memory') {
    const names = ((dut.mod && dut.mod.params) || []).map(p => p.name);
    const o = {};
    const aw = names.find(n => /^(ADDR_WIDTH|AW|ADDR_W|PTR_WIDTH|PTR_W|LOG2_DEPTH|DEPTH_LOG2)$/i.test(n));
    const dp = names.find(n => /^(DEPTH|FIFO_DEPTH|SIZE)$/i.test(n));
    const dw = names.find(n => /^(DATA_WIDTH|DW|DATA_W|WIDTH|WORD_WIDTH|DWIDTH)$/i.test(n));
    if (aw) o[aw] = 2; else if (dp) o[dp] = 4;
    if (dw) o[dw] = 4;
    if (Object.keys(o).length) {
      small = o; dut = tb.resolveDut(cfg, root, o, read);
      // the model must use the small depth too (a localparam DEPTH derived inside the RTL is not re-evaluated here)
      cfg.behavior = Object.assign({}, cfg.behavior, { depth: 4 });
    }
  }
  const model = tb.buildModel(cfg, dut.ports, dut.paramValues);
  const top = cfg.dut.top, name = `${top}_formal`;
  // what the generated harness cannot express (yet): say so instead of producing something wrong
  const placeholder = cfg.template === 'custom' && Object.values((cfg.behavior && cfg.behavior.checks) || {}).some(v => /\/\*\s*expected/.test(String(v)));
  const why = model.checkCode ? 'the pipeline template checks through a transaction queue, which is not synthesizable for formal; use SVA properties for pipelines'
    : model.latch ? 'latches are not supported by the generated formal harness'
    : model.seq && !(cfg.reset && cfg.reset.name) ? 'a sequential DUT without a reset port has an unknown start state; add a reset to prove it'
    : placeholder ? 'the custom template\'s reference model is still a placeholder (dvflow.json → behavior.checks)'
    : !(model.checks || []).length ? 'the template defines no output checks' : null;
  if (why) return { supported: false, reason: why, files: {}, asserts: [], covers: [] };

  const L = [];
  const asserts = [], covers = [];
  const w = p => (p.width > 1 ? `[${p.width - 1}:0] ` : '');
  const rst = cfg.reset && cfg.reset.name, rstOn = rst ? (cfg.reset.active_low ? `!${rst}` : rst) : "1'b0";
  const clk = cfg.clock.name || 'clk', edge = cfg.clock.edge || 'posedge';
  const ins = dut.ports.filter(p => p.dir === 'input'), outs = dut.ports.filter(p => p.dir === 'output');
  const params = Object.entries(Object.assign({}, cfg.dut.params || {}, small || {}));
  L.push(`// Formal harness for ${top}: generated by 10xEngineers EDA (template "${cfg.template}").`);
  L.push('// The DUT and the reference model run side by side. Every DUT input is a free input, so the solver explores');
  L.push('// every value on every cycle; each assertion says "this output equals the model", each cover asks "can this bin happen".');
  L.push(`module ${name} (`);
  ins.forEach((p, i) => L.push(`  input logic ${w(p)}${p.name}${i < ins.length - 1 ? ',' : ''}`));   // one line each: assertion/cover line numbers must be exact
  L.push(');');
  outs.forEach(p => L.push(`  logic ${w(p)}${p.name};`));
  L.push(`  ${top}${params.length ? ` #(${params.map(([k, v]) => `.${k}(${v})`).join(', ')})` : ''} dut (${dut.ports.map(p => `.${p.name}(${p.name})`).join(', ')});`);
  L.push('');
  L.push('  // the testbench\'s view of the inputs (the model code reads in_<port>)');
  model.inputs.forEach(i => L.push(`  logic ${i.width > 1 ? `[${i.width - 1}:0] ` : ''}in_${i.name};`));
  L.push('  always @* begin');
  model.inputs.forEach(i => L.push(`    in_${i.name} = ${i.name};`));
  L.push('  end');
  L.push('');
  L.push('  // reference model');
  String(model.decl || '').split('\n').filter(Boolean).forEach(l => L.push(l));
  let ready;
  if (model.seq) {
    L.push('  reg f_init = 1\'b1;   // first cycle: the design starts in reset');
    L.push(`  always @(${edge} ${clk}) f_init <= 1'b0;`);
    L.push(`  always @* if (f_init) assume (${rstOn});`);
    L.push(`  always @(${edge} ${clk}) begin`);
    L.push(`    if (${rstOn}) begin`);
    String(model.preReset || '').split('\n').filter(Boolean).forEach(l => L.push('    ' + l.trim()));
    String(model.reset || '').split('\n').filter(Boolean).forEach(l => L.push('      ' + l.trim()));
    L.push('    end else begin');
    String(model.step || '').split('\n').filter(Boolean).forEach(l => L.push('      ' + l.trim()));
    String(model.postBins || '').split('\n').filter(Boolean).forEach(l => L.push('      ' + l.trim()));
    L.push('    end');
    L.push('  end');
    ready = `!f_init && !(${rstOn})`;
  } else {
    L.push('  always @* begin');
    String(model.step || '').split('\n').filter(Boolean).forEach(l => L.push('    ' + l.trim()));
    L.push('  end');
    ready = "1'b1";
  }
  L.push('');
  L.push('  // checks: every checked output equals the model');
  L.push('  // (left out of the cover task: there, assertions would act as assumptions and hide the inputs that expose a bug)');
  L.push('`ifndef FORMAL_COVER');
  L.push('  always @* begin');
  L.push(`    if (${ready}) begin`);
  for (const c of model.checks) {
    const id = (model.checkers || []).find(k => k.signal === c.name);
    const g = c.guard ? `if (${c.guard}) ` : '';
    L.push(`      ${g}assert (${c.name} == (${c.exp}));   // ${id ? id.id + ' ' : ''}${c.name}`);
    asserts.push({ line: L.length, signal: c.name, check: id ? id.id : `CHK-${c.name.toUpperCase()}`, exp: c.exp });
  }
  L.push('    end');
  L.push('  end');
  L.push('`endif');
  L.push('');
  L.push('  // covers: can each coverage bin of the test plan happen at all?');
  L.push('  always @* begin');
  L.push(`    if (${ready}) begin`);
  for (const b of model.bins || []) {
    if (/_hit\b/.test(b.cond)) { covers.push({ line: null, bin: b.id, desc: b.desc, skipped: 'tracked by a testbench flag, not expressible as a cover' }); continue; }
    L.push(`      cover (${b.cond});   // ${b.id}: ${b.desc}`);
    covers.push({ line: L.length, bin: b.id, desc: b.desc });
  }
  L.push('    end');
  L.push('  end');
  L.push('endmodule');
  const sv = L.join('\n') + '\n';
  // designs with storage (FIFO memory) rarely close by k-induction without hand-written invariants: run a bounded check deep
  // enough to fill, overflow, drain and wrap the pointers instead (2 x depth + 4 cycles), and say so in the report
  const bounded = model.depth ? 2 * model.depth + 4 : null;
  const depth = bounded || (model.seq ? 20 : 1);
  const dutFiles = cfg.dut.files.map(f => path.relative(path.join(root, 'formal'), path.resolve(root, f)).replace(/\\/g, '/'));
  const sby = `# SymbiYosys: ${top} vs its reference model, generated by 10xEngineers EDA
#   sby -f ${top}.sby prove    ${bounded ? `bounded check (${bounded} cycles from reset)` : 'unbounded proof (k-induction)'} that every output equals the model
#   sby -f ${top}.sby cover    which coverage bins can happen, with a trace for each
[tasks]
prove
cover

[options]
prove: mode ${bounded ? 'bmc' : 'prove'}
prove: depth ${depth}
cover: mode cover
cover: depth ${model.seq ? 24 : 2}

[engines]
smtbmc z3

[script]
cover: read -define FORMAL_COVER
${dutFiles.map(f => `read -formal ${path.basename(f)}`).join('\n')}
read -formal ${name}.sv
prep -top ${name}

[files]
${dutFiles.join('\n')}
${name}.sv
`;
  return { supported: true, top: name, files: { [`formal/${name}.sv`]: sv, [`formal/${top}.sby`]: sby }, asserts, covers, bounded, small, sby: `formal/${top}.sby` };
}

/** sby cover log -> {line: {reached, step, trace}} */
function parseCovers(text) {
  const out = {};
  // Yosys reports a statement's source span starting where the previous statement ended ("39.20-40.37" for line 40):
  // the END line of the span is the statement's own line
  const re = /(Reached|Unreached) cover statement at \S+?\.sv:(\d+)(?:\.\d+)?(?:-(\d+)\.\d+)?[^\n]*?(?: in step (\d+))?\.?$/gm;
  let m;
  while ((m = re.exec(String(text)))) {
    const line = +(m[3] || m[2]);
    if (!out[line] || m[1] === 'Reached') out[line] = { reached: m[1] === 'Reached', step: m[4] != null ? +m[4] : null };
  }
  return out;
}

module.exports = { generate, parseCovers };
